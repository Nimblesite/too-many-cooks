#!/usr/bin/env node
// [SWR-VSIX-BUNDLE] Build the too-many-cooks server as a Node single-executable
// application for ONE target, staged with everything it needs at runtime:
//
//   <outDir>/too-many-cooks[.exe]   pinned Node runtime + the bundled server
//   <outDir>/better_sqlite3.node    Node-API addon (shipped in better-sqlite3's tarball)
//   <outDir>/schema/                DataProvider YAML schema
//   <outDir>/dataprovider/<target>/ DataProviderMigrate (no .NET runtime)
//   <outDir>/package.json           the (release-stamped) version source
//
// The VSIX bundles this under bin/<target>/ so a clean machine needs no Node,
// npx, PATH lookup or network to start the server ([SWR-IDE-RESOLUTION]).
// The Node runtime is pinned in scripts/sea-node-version and verified against
// scripts/sea-node-SHA256SUMS (checked against the Node release signature when
// pinned). darwin targets must be built on macOS: injection breaks the code
// signature, and only macOS can re-sign.
//
// Usage: build-server-sea.mjs <target> <outDir>
import { execFileSync } from "node:child_process";
import { chmodSync, copyFileSync, cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { downloadVerified, extract, parseSums } from "./lib/fetch-verified.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WORKSPACE = join(ROOT, "too-many-cooks");
const PKG = join(WORKSPACE, "packages", "too-many-cooks");
const SCRIPTS = join(ROOT, "scripts");
const NODE_VERSION = readFileSync(join(SCRIPTS, "sea-node-version"), "utf8").trim();
const NODE_SUMS = parseSums(readFileSync(join(SCRIPTS, "sea-node-SHA256SUMS"), "utf8"));
const NODE_DIST = `https://nodejs.org/dist/v${NODE_VERSION}`;
const CACHE = join(WORKSPACE, ".sea-cache", NODE_VERSION);
const BINARY = "too-many-cooks";
const ADDON = "better_sqlite3.node";
const SEA_FUSE = "NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2";
const SEA_RESOURCE = "NODE_SEA_BLOB";
const MACHO_SEGMENT = "NODE_SEA";
const TARGETS = ["darwin-arm64", "darwin-x64", "linux-x64", "win32-x64"];
const workspaceRequire = createRequire(join(WORKSPACE, "package.json"));

const isWindows = (target) => target.startsWith("win32");
const isDarwin = (target) => target.startsWith("darwin");
const exeName = (target) => (isWindows(target) ? `${BINARY}.exe` : BINARY);

/** Node's dist naming: win32-x64 -> win-x64.zip, others -> <target>.tar.gz. */
const nodeArchive = (target) => (isWindows(target)
  ? { name: `node-v${NODE_VERSION}-win-x64.zip`, exe: join(`node-v${NODE_VERSION}-win-x64`, "node.exe") }
  : { name: `node-v${NODE_VERSION}-${target}.tar.gz`, exe: join(`node-v${NODE_VERSION}-${target}`, "bin", "node") });

/** Pinned Node runtime for `target`, downloaded once and SHA-256 verified. */
const nodeRuntime = async (target) => {
  const cached = join(CACHE, target, isWindows(target) ? "node.exe" : "node");
  if (existsSync(cached)) { return cached; }
  const { name, exe } = nodeArchive(target);
  const bytes = await downloadVerified(`${NODE_DIST}/${name}`, name, NODE_SUMS.get(name));
  const work = extract(name, bytes, "sea-node-");
  mkdirSync(dirname(cached), { recursive: true });
  copyFileSync(join(work, exe), cached);
  chmodSync(cached, 0o755);
  rmSync(work, { recursive: true, force: true });
  return cached;
};

/** One CJS file: SEA main scripts can only `require` builtins. `import.meta.url`
 *  becomes the executable's URL so package.json/schema lookups resolve beside it,
 *  and better-sqlite3 loads its addon with a real file-based require. */
const bundleServer = async (work) => {
  const entry = join(PKG, "build", "bin", "server.js");
  if (!existsSync(entry)) { throw new Error(`${entry} missing: build the server first`); }
  const outfile = join(work, "server.cjs");
  await workspaceRequire("esbuild").build({
    entryPoints: [entry],
    bundle: true,
    platform: "node",
    format: "cjs",
    target: `node${NODE_VERSION.split(".")[0]}`,
    outfile,
    logLevel: "warning",
    banner: {
      js: [
        'const __tmcRequire = require("node:module").createRequire(__filename);',
        'const __tmcModuleUrl = require("node:url").pathToFileURL(__filename).href;',
      ].join("\n"),
    },
    define: { "import.meta.url": "__tmcModuleUrl", __non_webpack_require__: "__tmcRequire" },
  });
  return outfile;
};

/** SEA blob generated by the SAME pinned Node version as the target runtime. */
const seaBlob = async (work, main) => {
  const hostNode = await nodeRuntime(`${process.platform}-${process.arch}`);
  const config = join(work, "sea-config.json");
  const output = join(work, "sea.blob");
  writeFileSync(config, JSON.stringify({
    main, output, disableExperimentalSEAWarning: true, useSnapshot: false, useCodeCache: false,
  }));
  execFileSync(hostNode, ["--experimental-sea-config", config], { stdio: "inherit" });
  return readFileSync(output);
};

/** Copy the target runtime to `exe` and inject the blob (re-signing on macOS). */
const injectBlob = async (target, exe, blob) => {
  copyFileSync(await nodeRuntime(target), exe);
  chmodSync(exe, 0o755);
  if (isDarwin(target)) { execFileSync("codesign", ["--remove-signature", exe], { stdio: "inherit" }); }
  await workspaceRequire("postject").inject(exe, SEA_RESOURCE, blob, {
    sentinelFuse: SEA_FUSE,
    ...(isDarwin(target) ? { machoSegmentName: MACHO_SEGMENT } : {}),
  });
  if (isDarwin(target)) { execFileSync("codesign", ["--sign", "-", exe], { stdio: "inherit" }); }
};

/** Everything the executable reads at runtime, beside it. */
const stageRuntimeFiles = (target, outDir) => {
  copyFileSync(join(workspaceRequire.resolve("better-sqlite3/package.json"), "..", "prebuilds", `${target}.node`), join(outDir, ADDON));
  cpSync(join(PKG, "schema"), join(outDir, "schema"), { recursive: true });
  cpSync(join(PKG, "dataprovider", target), join(outDir, "dataprovider", target), { recursive: true });
  copyFileSync(join(PKG, "package.json"), join(outDir, "package.json"));
};

const main = async () => {
  const [target, out] = process.argv.slice(2);
  if (!TARGETS.includes(target) || out === undefined) {
    throw new Error(`usage: build-server-sea.mjs <${TARGETS.join("|")}> <outDir>`);
  }
  if (isDarwin(target) && process.platform !== "darwin") { throw new Error(`${target} must be built on macOS (code signing)`); }
  const outDir = resolve(out);
  const work = mkdtempSync(join(tmpdir(), "tmc-sea-"));
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  await injectBlob(target, join(outDir, exeName(target)), await seaBlob(work, await bundleServer(work)));
  stageRuntimeFiles(target, outDir);
  rmSync(work, { recursive: true, force: true });
  process.stdout.write(`sea: built ${BINARY} for ${target} (Node ${NODE_VERSION}) in ${outDir}\n`);
};

await main();
